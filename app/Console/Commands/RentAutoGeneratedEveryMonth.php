<?php

namespace App\Console\Commands;

use App\Http\Utils\BasicUtil;
use App\Models\Rent;
use App\Models\TenancyAgreement;
use Carbon\Carbon;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Log;

class RentAutoGeneratedEveryMonth extends Command
{
    use BasicUtil;
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'rent:generate-due';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Generate rent entries after rent due day if not already created';

    /**
     * Create a new command instance.
     *
     * @return void
     */
    public function __construct()
    {
        parent::__construct();
    }

    /**
     * Execute the console command.
     *
     * @return int
     */
    public function handle()
    {


        // GET AGREEMENTS ONLY WHERE  PAYMENT OPTION -> per_calendar_month
        $agreements = TenancyAgreement::with(['property', 'rents'])
            ->whereHas('property', function ($query) {
                $query->whereNull('deleted_at');
            })
            ->whereNotNull('rent_due_day')
            ->whereNotNull('tenant_contact_expired_date')
            ->whereDate('tenant_contact_expired_date', '>', today())
            ->get();



        foreach ($agreements as $agreement) {
        $createdBy = (int) optional($agreement->property)->created_by;
       $pyment_data = $this->calculatePayments($agreement, today()->copy());

    $arrear = $pyment_data["total_arrears"];
    $payment_date = Carbon::parse($pyment_data["last_passed_due_date"]);

    if($arrear > 0) {
  $rent_data = [
                    'tenancy_agreement_id' => $agreement->id,
                    'year' => $payment_date->year,
                    'month' => $payment_date->month,
                    'rent_amount' => $agreement->agreed_rent,
                    'paid_amount' => 0,
                    'arrear' => $arrear,
                    'payment_status' => 'pending',
                    'payment_date' => $pyment_data["last_passed_due_date"],
                    'payment_method' => "",
                    'rent_taken_by' => "",
                    'remarks' => 'This rent is auto generated and due on ' . $payment_date->toDateString(),
                    'created_by' => $createdBy,

            ];

            Rent::where('tenancy_agreement_id', $agreement->id)->where('payment_status', "pending")->delete();

            $rent =  Rent::create($rent_data);
    }


            $this->info("Rent" . json_encode($rent) . " created");




            }


        return 0;

    }

}
